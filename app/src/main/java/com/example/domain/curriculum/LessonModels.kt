enum class LessonCategory(val title: String) {
  BASICS("Первые шаги"),
  CAPTURES("Искусство боя"),
  KING("Сила Дамки"),
  STRATEGY("Хитрости стратегии"),
  TOURNAMENT("Школа разрядника и турнир"),
  OPENINGS("Дебютный тренажёр"),
}

enum class LessonFolder(val title: String, val subtitle: String, val badgeText: String) {
  BEGINNER("Для начинающих", "Базовые 17 уроков: правила, удары, дамка и первые дебюты", "1–17"),
  TACTICIAN("Хитрый Тактик", "15 уроков тактики: вилки, жертвы, ловля дамок и борьба за центр", "Тактик"),
  GRANDMASTER("Гроссмейстер", "15 уроков и задач: цугцванг, многоходовые каскады и эндшпиль", "Гросс"),
}

data class DemoStep(
  val caption: String,
  val move: CheckersMove? = null,
  val highlightSquares: List<Square> = emptyList(),
)

data class InteractiveLesson(
  val id: String,
  val order: Int,
  val title: String,
  val subtitle: String,
  val category: LessonCategory,
  val folder: LessonFolder = LessonFolder.BEGINNER,
  val shortRule: String,
  val mascotTip: String,
  val demoInitialRows: List<String>,
  val demoSteps: List<DemoStep>,
  val exercisePrompt: String,
  val exerciseInitialRows: List<String>,
  val playerColor: PieceColor = PieceColor.WHITE,
  val acceptedMoveNotations: Set<String>,
  val hintMove: CheckersMove,
  val hintText: String,
  val successFeedback: String,
  val suboptimalMoveHint: String,
  val starsReward: Int = 2,
) {
  fun demoBoard(): CheckersBoard = CheckersBoard.fromStrings(demoInitialRows)
  fun exerciseBoard(): CheckersBoard = CheckersBoard.fromStrings(exerciseInitialRows)
}

